<#
.SYNOPSIS
    Regenerates docs/DEPENDENCIES.md: SDK, every NuGet package (direct and transitive) per project,
    and the model inventory (BLUEPRINT §10 Phase 0A, §13).

.DESCRIPTION
    Run after any package or model change, then review THIRD_PARTY_NOTICES.md.
    Requires a successful restore (run scripts/build.ps1 or dotnet restore first).
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$outFile = Join-Path $root 'docs\DEPENDENCIES.md'

Push-Location $root
try {
    $sdk = (Get-Content global.json -Raw | ConvertFrom-Json).sdk.version
    $json = dotnet list IrisAura.sln package --include-transitive --format json 2>$null
    if ($LASTEXITCODE -ne 0) {
        # The full solution includes a .vcxproj the dotnet CLI cannot load without Visual Studio;
        # fall back to listing each C# project.
        $projects = (Get-Content IrisAura.Managed.slnf -Raw | ConvertFrom-Json).solution.projects
        $all = foreach ($p in $projects) {
            $j = dotnet list $p package --include-transitive --format json | ConvertFrom-Json
            if ($LASTEXITCODE -ne 0) { throw "dotnet list package failed for $p" }
            $j.projects
        }
    }
    else {
        $all = ($json | ConvertFrom-Json).projects
    }

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('# Dependency Inventory')
    $lines.Add('')
    $lines.Add('> Generated by `scripts/generate-dependency-inventory.ps1`. Do not edit by hand.')
    $lines.Add('')
    $lines.Add('## Toolchain')
    $lines.Add('')
    $lines.Add("- .NET SDK: ``$sdk`` (pinned in ``global.json``, roll forward: latest patch)")
    $lines.Add('- Native: MSVC via Visual Studio (`$(DefaultPlatformToolset)`), C++20, latest installed Windows SDK')
    $lines.Add('- NuGet source: nuget.org only (`nuget.config`, package source mapping)')
    $lines.Add('')
    $lines.Add('## NuGet packages by project')
    $lines.Add('')
    $lines.Add('| Project | Framework | Package | Requested | Resolved | Kind |')
    $lines.Add('|---|---|---|---|---|---|')

    $count = 0
    foreach ($proj in ($all | Sort-Object { Split-Path $_.path -Leaf })) {
        $name = [IO.Path]::GetFileNameWithoutExtension($proj.path)
        foreach ($fw in $proj.frameworks) {
            foreach ($pkg in $fw.topLevelPackages) {
                $lines.Add("| $name | $($fw.framework) | $($pkg.id) | $($pkg.requestedVersion) | $($pkg.resolvedVersion) | direct |"); $count++
            }
            foreach ($pkg in $fw.transitivePackages) {
                $lines.Add("| $name | $($fw.framework) | $($pkg.id) |  | $($pkg.resolvedVersion) | transitive |"); $count++
            }
        }
    }
    if ($count -eq 0) { $lines.Add('| — | — | (none) | | | |') }

    $lines.Add('')
    $lines.Add('## Models')
    $lines.Add('')
    $sums = Join-Path $root 'models\SHA256SUMS'
    $modelLines = @()
    if (Test-Path $sums) { $modelLines = @(Get-Content $sums | Where-Object { $_.Trim() }) }
    if ($modelLines.Count -eq 0) {
        $lines.Add('No models are included yet (see `models/README.md`).')
    }
    else {
        $lines.Add('| SHA-256 | File |'); $lines.Add('|---|---|')
        foreach ($l in $modelLines) { $parts = $l -split '\s+', 2; $lines.Add("| ``$($parts[0])`` | $($parts[1].TrimStart('*')) |") }
    }

    [IO.File]::WriteAllText($outFile, ($lines -join "`r`n") + "`r`n", [Text.UTF8Encoding]::new($false))
    Write-Host "Wrote $outFile ($count package entries)."
}
finally {
    Pop-Location
}
